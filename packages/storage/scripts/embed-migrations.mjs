// Embeds drizzle-kit's SQL migrations into src/migrations.generated.ts so the
// bundled Electron app needs no migrations folder on disk.
// Run via `pnpm --filter @rka/storage db:generate` (or `db:embed`).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'drizzle');
const outFile = join(root, 'src', 'migrations.generated.ts');

const journal = JSON.parse(readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'));

const migrations = journal.entries.map((entry) => {
  // Normalise line endings so the hash is identical on Windows and Linux.
  const sql = readFileSync(join(migrationsDir, `${entry.tag}.sql`), 'utf8').replace(/\r\n/g, '\n');
  return {
    tag: entry.tag,
    hash: createHash('sha256').update(sql).digest('hex'),
    statements: sql
      .split('--> statement-breakpoint')
      .map((s) => s.trim())
      .filter(Boolean),
  };
});

const body = `// GENERATED by scripts/embed-migrations.mjs from ./drizzle - do not edit by hand.
// Regenerate with: pnpm --filter @rka/storage db:generate

export interface EmbeddedMigration {
  readonly tag: string;
  readonly hash: string;
  readonly statements: readonly string[];
}

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(outFile, body);
console.log(`Embedded ${migrations.length} migration(s) into src/migrations.generated.ts`);
