import { z } from 'zod';

/*
 * Provider-neutral request/response contract. Nothing here is Ollama-specific;
 * provider implementations translate to and from their own wire format.
 */

// -----------------------------------------------------------------------------
// Tool calling
// -----------------------------------------------------------------------------

/** Tool names as models and Ollama accept them: letters, digits, `_` and `-`. */
export const ToolNameSchema = z.string().regex(/^[A-Za-z][A-Za-z0-9_-]{0,63}$/, {
  message: 'Tool names start with a letter and use only letters, digits, "_" and "-" (max 64).',
});

/** A tool the model may call. `parameters` is a JSON Schema for an object. */
export const ToolDefinitionSchema = z.strictObject({
  name: ToolNameSchema,
  description: z.string().trim().min(1).max(2048),
  parameters: z.record(z.string(), z.unknown()).refine((schema) => schema['type'] === 'object', {
    message: 'Tool parameters must be a JSON Schema with type "object".',
  }),
});
export type ToolDefinition = z.infer<typeof ToolDefinitionSchema>;

/** A complete, structurally valid tool call requested by the model. */
export const ToolCallSchema = z.strictObject({
  /** Server-assigned id, or one generated by the provider when the server sends none. */
  id: z.string().min(1).max(256),
  name: ToolNameSchema,
  /** Parsed JSON object. Not yet validated against the tool's own schema. */
  arguments: z.record(z.string(), z.unknown()),
});
export type ToolCall = z.infer<typeof ToolCallSchema>;

/** Why a tool call from the model could not be accepted. */
export type InvalidToolCallReason = 'unknown-tool' | 'malformed-arguments';

/**
 * A tool call the provider rejected (never executable). The caller should
 * answer it with a tool-result message describing the error so the model can
 * correct itself.
 */
export interface InvalidToolCall {
  readonly id: string;
  /** The name as sent by the model (may not be a declared tool). */
  readonly name: string;
  readonly reason: InvalidToolCallReason;
  readonly message: string;
  /** The raw arguments as received, truncated, for logging. */
  readonly rawArguments: string;
}

// -----------------------------------------------------------------------------
// Messages
// -----------------------------------------------------------------------------

const TextMessageSchema = z.object({
  role: z.enum(['system', 'user']),
  content: z.string(),
});

const AssistantMessageSchema = z.object({
  role: z.literal('assistant'),
  content: z.string(),
  /** Tool calls the model made in this turn (replayed as conversation history). */
  toolCalls: z.array(ToolCallSchema).min(1).max(64).optional(),
});

/** The result of one tool call, returned to the model. */
const ToolResultMessageSchema = z.object({
  role: z.literal('tool'),
  /** The id of the tool call this message answers. */
  toolCallId: z.string().min(1).max(256),
  /** The tool's name (older Ollama servers match results by name). */
  name: ToolNameSchema,
  /** The result as text, usually JSON. */
  content: z.string(),
});

export const ChatMessageSchema = z.union([
  TextMessageSchema,
  AssistantMessageSchema,
  ToolResultMessageSchema,
]);
export type ChatMessage = z.infer<typeof ChatMessageSchema>;
export type ToolResultMessage = z.infer<typeof ToolResultMessageSchema>;

export const ResponseFormatSchema = z.discriminatedUnion('type', [
  z.object({ type: z.literal('text') }),
  /** Any valid JSON. */
  z.object({ type: z.literal('json') }),
  /** JSON constrained by a JSON Schema. */
  z.object({ type: z.literal('json_schema'), schema: z.record(z.string(), z.unknown()) }),
]);
export type ResponseFormat = z.infer<typeof ResponseFormatSchema>;

export const GenerationOptionsSchema = z.strictObject({
  temperature: z.number().min(0).max(2).optional(),
  topP: z.number().gt(0).max(1).optional(),
  /** Only the K most likely tokens are considered. */
  topK: z.int().min(1).max(1000).optional(),
  /** Penalises repeated tokens (1 = off). */
  repeatPenalty: z.number().min(0).max(2).optional(),
  seed: z.int().optional(),
  /** Maximum tokens to generate. */
  maxTokens: z.int().positive().optional(),
  /** Context window in tokens. Defaults to the provider's configured value. */
  contextLength: z.int().min(512).max(1_048_576).optional(),
  stop: z.array(z.string().min(1)).max(8).optional(),
});
export type GenerationOptions = z.infer<typeof GenerationOptionsSchema>;

export const GenerateRequestSchema = z
  .strictObject({
    /** Defaults to the provider's configured model. */
    model: z.string().trim().min(1).optional(),
    messages: z.array(ChatMessageSchema).min(1),
    responseFormat: ResponseFormatSchema.optional(),
    options: GenerationOptionsSchema.optional(),
    /** Enable model "thinking" output. Off by default; only some models support it. */
    think: z.boolean().optional(),
    /**
     * Tools the model may call. The provider only returns validated tool calls;
     * it never executes anything. Rejected unless the provider was created with
     * tool calling allowed.
     */
    tools: z.array(ToolDefinitionSchema).min(1).max(64).optional(),
  })
  .superRefine((req, ctx) => {
    const names = new Set<string>();
    for (const [i, tool] of (req.tools ?? []).entries()) {
      if (names.has(tool.name)) {
        ctx.addIssue({
          code: 'custom',
          path: ['tools', i, 'name'],
          message: `Duplicate tool "${tool.name}".`,
        });
      }
      names.add(tool.name);
    }
    // Every tool result must answer a call made by an earlier assistant message.
    const callIds = new Set<string>();
    for (const [i, message] of req.messages.entries()) {
      if (message.role === 'assistant') {
        for (const call of message.toolCalls ?? []) {
          if (callIds.has(call.id)) {
            ctx.addIssue({
              code: 'custom',
              path: ['messages', i],
              message: `Duplicate tool call id "${call.id}".`,
            });
          }
          callIds.add(call.id);
        }
      }
      if (message.role === 'tool' && !callIds.has(message.toolCallId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['messages', i, 'toolCallId'],
          message: `Tool result for unknown tool call id "${message.toolCallId}".`,
        });
      }
    }
  });
export type GenerateRequest = z.input<typeof GenerateRequestSchema>;

export type FinishReason = 'stop' | 'length' | 'other';

export interface Usage {
  readonly promptTokens: number | null;
  readonly completionTokens: number | null;
  readonly totalDurationMs: number | null;
  readonly loadDurationMs: number | null;
}

export interface GenerateResult {
  readonly model: string;
  readonly content: string;
  /** Present only when thinking was requested and returned. */
  readonly thinking?: string;
  readonly finishReason: FinishReason;
  /**
   * Tool calls requested by the model, in order. Present (non-empty) only when
   * the request declared tools and the model called at least one. In a stream,
   * tool calls are delivered only here, in the final `done` chunk, after the
   * whole response has arrived and every call has been parsed.
   */
  readonly toolCalls?: readonly ToolCall[];
  /** Tool calls that could not be accepted (unknown tool, malformed arguments). */
  readonly invalidToolCalls?: readonly InvalidToolCall[];
  readonly usage: Usage;
}

export type GenerateChunk =
  | { readonly type: 'delta'; readonly content: string; readonly thinking?: string }
  | { readonly type: 'done'; readonly result: GenerateResult };

export interface CallOptions {
  /** Abort to cancel. Surfaces as a `cancelled` error. */
  readonly signal?: AbortSignal;
  /** Overall deadline. Surfaces as a `timeout` error. */
  readonly timeoutMs?: number;
  /** Streams only: maximum silence between chunks. Surfaces as a `timeout` error. */
  readonly idleTimeoutMs?: number;
}

export interface ModelInfo {
  readonly name: string;
  readonly capabilities: readonly string[];
  readonly contextLength: number | null;
  readonly parameterSize: string | null;
  readonly quantization: string | null;
}

export type ModelAvailability =
  | { readonly available: true; readonly model: ModelInfo }
  | {
      readonly available: false;
      readonly requested: string;
      readonly installedModels: readonly string[];
    };
